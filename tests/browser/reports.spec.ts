import { expect, test, type Page } from '@playwright/test'
import JSZip from 'jszip'
import { mockAccountApi } from './mock-api'
import { multipointWorkbook } from '../multipoint-fixture'

test.beforeEach(async ({ page }) => mockAccountApi(page))
async function start(page: Page) {
  await page.goto('/tests/browser/fixture.html')
  await page.getByLabel('Arquivo de medições').setInputFiles({ name: 'pontos-sinteticos.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from(multipointWorkbook(['P1', 'P2'], [60, 60])) })
  await page.getByRole('button', { name: 'Gerar gráfico', exact: true }).click()
  await page.getByRole('button', { name: 'Criar documento', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Editor de documento' })).toBeVisible()
  await expect(page.getByRole('navigation').getByText('Documentos', { exact: true })).toHaveCount(0)
}
async function add(page: Page, kind: string) {
  const rows = page.locator('.report-paper .report-row-group')
  if (await rows.count()) await rows.last().locator(':scope > .report-insert-point button').click()
  else await page.getByRole('button', { name: 'Adicionar conteúdo', exact: true }).click()
  await page.getByRole('menuitem', { name: kind, exact: true }).click()
}
async function showTools(page: Page) {
  const toggle = page.getByRole('button', { name: 'Ferramentas e páginas', exact: true })
  if (await toggle.isVisible() && await toggle.getAttribute('aria-expanded') === 'false') await toggle.click()
}

