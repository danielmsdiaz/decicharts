test('importação, duplicados, filtros, zoom, PNG/SVG, tema e logout', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/tests/browser/fixture.html')
  await expect(page.getByRole('button', { name: 'Selecionar arquivo', exact: true })).toBeEnabled()
  await importCsv(page)
  await page.screenshot({ animations: 'disabled', path: '/tmp/decicharts-redesign-chart-default.png', fullPage: true })
  const stats = page.locator('dl')
  await expect(stats).toContainText('50,5 dB')
  await expect(stats).toContainText('70,0 dB')
  await expect(page.getByText(/1 registros inválidos excluídos/)).toBeVisible()
  await expect(page.getByText(/1 tempos repetidos preservados/)).toBeVisible()
  await page.getByText('Ajustar período e título', { exact: true }).click()
  await page.getByLabel('Título do gráfico').fill('Medição ambiental — Ponto 1')
  await page.getByLabel('Início', { exact: true }).fill('2026-11-23T12:00:01.000')
  await page.getByLabel('Fim', { exact: true }).fill('2026-11-23T12:00:01.000')
  await page.getByRole('button', { name: 'Aplicar intervalo' }).click()
  await expect(stats).toContainText('65,4 dB')
  await expect(page.getByTestId('measurement-count')).toHaveText('2')
  const exportButton = page.getByRole('button', { name: 'Exportar figura', exact: true })
  const exportDialog = page.getByRole('dialog', { name: 'Exportar figura' })
  for (const format of ['SVG', 'PNG']) {
    await exportButton.click()
    await exportDialog.getByText(format, { exact: true }).click()
    const image = exportDialog.getByRole('img', { name: 'Prévia da figura a baixar' })
    await expect.poll(() => image.evaluate(node => node instanceof HTMLImageElement && node.naturalWidth)).toBe(format === 'PNG' ? 1920 : 960)
    const previewHash = await image.evaluate(async node => {
      const bytes = await (await fetch((node as HTMLImageElement).src)).arrayBuffer()
      const hash = await crypto.subtle.digest('SHA-256', bytes)
      return Array.from(new Uint8Array(hash), byte => byte.toString(16).padStart(2, '0')).join('')
    })
    const downloadPromise = page.waitForEvent('download')
    await exportDialog.getByRole('button', { name: `Baixar ${format}` }).click()
    const download = await downloadPromise
    await expect(exportDialog).toBeHidden()
    expect(download.suggestedFilename()).toBe(`decicharts-medicao.${format.toLowerCase()}`)
    const data = await readFile((await download.path())!)
    expect(createHash('sha256').update(data).digest('hex')).toBe(previewHash)
    if (format === 'SVG') {
      const svg = data.toString('utf8')
      expect(svg).toContain('<svg')
      expect(svg).toContain('viewBox="0 0 960 1080"')
      expect(svg).toContain('Medição ambiental')
      expect(svg).toContain('America/Recife')
      expect(svg).toContain('Nível sonoro (dB)')
      expect(svg).toContain('12:00:01.000')
      expect(svg).not.toContain('22/11')
      expect(svg).not.toContain('24/11')
      await download.saveAs('/tmp/decicharts-selected.svg')
    } else {
      expect(data.subarray(1, 4).toString()).toBe('PNG')
      expect(data.readUInt32BE(16)).toBe(1920)
      expect(data.readUInt32BE(20)).toBe(2160)
      await download.saveAs('/tmp/decicharts-selected.png')
    }
  }
  await page.getByRole('button', { name: 'Restaurar', exact: true }).click()
  await expect(page.getByTestId('measurement-count')).toHaveText('4')
  await page.getByLabel('Início', { exact: true }).fill('2026-11-23T12:00:03.000')
  await page.getByLabel('Fim', { exact: true }).fill('2026-11-23T12:00:05.000')
  await page.getByRole('button', { name: 'Aplicar intervalo' }).click()
  await expect(exportButton).toBeDisabled()
  await expect(page.getByText('Não há medições neste intervalo.', { exact: false })).toBeVisible()
  await page.getByRole('button', { name: 'Restaurar', exact: true }).click()
  const chart = page.getByRole('img', { name: /Nível sonoro em/ })
  await chart.scrollIntoViewIfNeeded()
  const box = (await chart.boundingBox())!
  const originalStart = await page.getByLabel('Início', { exact: true }).inputValue()
  await page.mouse.move(box.x + box.width / 2, box.y + 160)
  await page.keyboard.down('Control')
  await page.mouse.wheel(0, -500)
  await page.keyboard.up('Control')
  await expect(page.getByLabel('Início', { exact: true })).not.toHaveValue(originalStart)
  await page.getByRole('button', { name: 'Restaurar', exact: true }).click()
  await page.screenshot({ animations: 'disabled', path: '/tmp/decicharts-desktop.png', fullPage: true })
  await page.getByRole('button', { name: 'Ativar tema escuro' }).click()
  await expect(page.locator('html')).toHaveClass('dark')
  await page.screenshot({ animations: 'disabled', path: '/tmp/decicharts-dark.png', fullPage: true })
  await page.getByRole('button', { name: 'Menu da conta' }).click()
  await page.getByRole('button', { name: 'Sair', exact: true }).click()
  await page.getByRole('alertdialog').getByRole('button', { name: 'Sair da conta', exact: true }).click()
  await expect(page.getByText('Sessão de teste encerrada')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Nível sonoro ao longo do tempo' })).toHaveCount(0)
  expect(errors).toEqual([])
})

